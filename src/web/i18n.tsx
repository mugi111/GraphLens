type I18nContextValue = { locale: Locale; setLocale: (locale: Locale) => void; t: (message: string) => string };
const I18nContext = createContext<I18nContextValue>({ locale: 'en', setLocale: () => undefined, t: message => message });
export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => {
    const saved = localStorage.getItem('graphlens.locale');
    return saved === 'ja' || saved === 'en' ? saved : navigator.language.toLowerCase().startsWith('ja') ? 'ja' : 'en';
  });
  const setLocale = (next: Locale) => { localStorage.setItem('graphlens.locale', next); setLocaleState(next); };
  const t = (message: string) => locale === 'ja' ? messages[message] ?? message : message;
  return <I18nContext.Provider value={{ locale, setLocale, t }}>{children}</I18nContext.Provider>;
}
export function useI18n() { return useContext(I18nContext); }
